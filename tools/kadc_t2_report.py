def base(run):
    return max(('A', 'c_a2'), key=lambda k: np.mean([x['acc'][k] for x in t2[run].values()]))


def paired(run, k):
    b, ds, ps, boots = base(run), [], [], []
    for x in t2[run].values():
        y = x['pred']['y']
        p, q = x['pred']['preds'][k] == y, x['pred']['preds'][b] == y
        n, n10, n01 = y.numel(), int((p & ~q).sum()), int((~p & q).sum())
        ds.append(100.0 * (n10 - n01) / n)
        ps.append(binomtest(n10, n10 + n01, 0.5).pvalue if n10 + n01 else 1.0)
        d = rng.multinomial(n, [n10 / n, n01 / n, 1 - (n10 + n01) / n], size=B)
        boots.append(100.0 * (d[:, 0] - d[:, 1]) / n)
    lo, hi = np.percentile(np.mean(boots, axis=0), [2.5, 97.5])
    return ds, ps, lo, hi


